// Regenerates the embedded sql.js block at the end of main.js from the vendored
// sql-wasm.js and sql-wasm.wasm. Run from the repo root after a sql.js bump:
//
//   node scripts/embed-sql-js.mjs
//
// sql-wasm.js goes in as code, verbatim, inside a function (no `new Function`,
// no eval: the Obsidian directory's review refuses both). The wasm stays a
// base64 string. A gate in test/engine.test.mjs asserts both copies match the
// vendored files byte for byte.
import { readFileSync, writeFileSync } from 'node:fs';

const BEGIN = '/* BEGIN embedded sql.js: generated by scripts/embed-sql-js.mjs, do not edit. */';
const END = '/* END embedded sql.js */';

const js = readFileSync('sql-wasm.js', 'utf8');
const wasm = readFileSync('sql-wasm.wasm').toString('base64');
if (js.includes(END)) throw new Error('sql-wasm.js contains the end marker');

const block = [
  BEGIN,
  '/* sql.js, vendored unmodified (see THIRD-PARTY-NOTICES.md). sql-wasm.js is a UMD',
  ' * build: given a `module` it exports initSqlJs. `require`, `__dirname` and',
  ' * `__filename` ride along for its Node branch (Electron computes them eagerly',
  ' * even though the wasm arrives as bytes); a plain web view never asks. */',
  'function sqlJsModule(nodeRequire) {',
  '  const mod = { exports: {} };',
  '  /* Parameters, not constants: the build assigns to some of these names. */',
  '  (function (module, exports, require, __dirname, __filename) {',
  '  /* ---- sql-wasm.js, verbatim, from here ---- */',
  js,
  '  /* ---- sql-wasm.js ends here ---- */',
  "  })(mod, mod.exports, nodeRequire, '/', '/sql-wasm.js');",
  '  return mod.exports;',
  '}',
  `const EMBEDDED_SQL_WASM_B64 = '${wasm}';`,
  END,
].join('\n');

const main = readFileSync('main.js', 'utf8');
const a = main.indexOf(BEGIN);
const b = main.indexOf(END);
if (a < 0 || b < a) throw new Error('markers not found in main.js');
writeFileSync('main.js', main.slice(0, a) + block + main.slice(b + END.length));
console.log('main.js: embedded sql.js regenerated');
